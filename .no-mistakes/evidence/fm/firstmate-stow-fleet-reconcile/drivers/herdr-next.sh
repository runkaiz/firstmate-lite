pane=$(jq -r .result.root_pane.pane_id "$CASE/workspace.json")
workspace=$(jq -r .result.workspace.workspace_id "$CASE/workspace.json")
tab=$(jq -r .result.tab.tab_id "$CASE/workspace.json")
sed -i "s/^backend=tmux$/backend=herdr/;s@^window=.*@window=$lab:$pane@" "$FM_HOME/state/$ID.meta"
printf 'herdr_session=%s\nherdr_workspace_id=%s\nherdr_tab_id=%s\nherdr_pane_id=%s\n' "$lab" "$workspace" "$tab" "$pane" >> "$FM_HOME/state/$ID.meta"
step bash bin/fm-herdr-lab.sh run "$lab" pane process-info --pane "$pane"
mkdir -p "$WT/build"
printf 'Herdr generated bytes\n' > "$WT/build/output"
refuse td
(cd "$WT"; exec sleep 300) &
foreign=$!
if td --preserve-untracked build; then kill "$foreign"; echo 'ERROR: foreign process did not refuse'; exit 1; fi
check test -d "$WT"
check test -f "$WT/build/output"
check test ! -e "$FM_HOME/data/$ID/preserved-artifacts"
check kill -0 "$foreign"
step bash bin/fm-herdr-lab.sh run "$lab" pane list
kill "$foreign"; wait "$foreign" || true
td --preserve-untracked build
closed
step cat "$FM_HOME/data/$ID/preserved-artifacts/files/build/output"
check test "$(cat "$FM_HOME/data/$ID/preserved-artifacts/files/build/output")" = 'Herdr generated bytes'
echo 'SCENARIO PASS: real Herdr shell closes; foreign process refuses preservation; after it exits, cleanup preserves bytes and closes queue'
